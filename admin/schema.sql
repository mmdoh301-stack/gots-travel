create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  reference_code text not null unique,
  name varchar(150) not null,
  email varchar(190) not null,
  travel_date date,
  guests smallint not null default 1 check (guests between 1 and 50),
  tour varchar(190) not null,
  message text,
  status text not null default 'new' check (status in ('new','contacted','confirmed','cancelled')),
  created_at timestamptz not null default now()
);

alter table public.bookings enable row level security;

-- Public visitors cannot read or modify bookings. Booking creation is performed
-- only by the Vercel serverless function using the secret service-role key.
-- Authenticated dashboard users can read/update bookings.
drop policy if exists "Admins can read bookings" on public.bookings;
create policy "Admins can read bookings"
on public.bookings for select to authenticated using (true);

drop policy if exists "Admins can update bookings" on public.bookings;
create policy "Admins can update bookings"
on public.bookings for update to authenticated using (true) with check (true);

grant select, update on public.bookings to authenticated;
grant usage, select on sequence public.bookings_id_seq to authenticated;
